"""Page 6 — Training Planner: evidence-backed combined programme suggestions."""

from __future__ import annotations

from datetime import date

import pandas as pd
import streamlit as st

from config.settings import SETTINGS
from dashboard.components import chart, download_csv, download_json, page_header, rules_table, safe_mining
from dashboard.state import AppContext
from src.mining.lift_filter import filter_rules, rank_rules
from src.recommendations.training_recommender import RecommendationResult, recommend, role_skill_gap
from src.visualization import charts

DISCLAIMER = (
    "Recommendations reflect how often skills are requested together in the analysed job postings. "
    "They indicate employer demand patterns, not guaranteed employment outcomes."
)


def render(ctx: AppContext) -> None:
    page_header("Training Planner", "Select skills a learner already has to see which complementary skills employers request with them.", ctx)
    st.caption(DISCLAIMER)
    outcome = safe_mining(ctx)
    freq = ctx.frequency()

    selected = st.multiselect(
        "Learner's existing skills", freq["skill"].tolist(), default=["python"] if "python" in set(freq["skill"]) else [],
        format_func=lambda s: f"{ctx.labels.get(s, s)}", key="tp_skills", placeholder="Choose one or more skills",
    )
    if not selected:
        st.info("Select at least one skill to generate recommendations.")
        return

    cfg = ctx.mining_config
    with st.expander("Evidence thresholds for recommendations", icon=":material/tune:"):
        st.caption("Applied to the rules already generated by the current mining run (support ≥ "
                   f"{cfg.min_support:.3f}). Lift is kept ≥ 1.0 so only positive associations are used.")
        c1, c2 = st.columns(2)
        min_conf = c1.slider("Minimum confidence", min_value=0.05, max_value=0.95, value=float(cfg.min_confidence),
                             step=0.05, key="tp_conf")
        min_lift = c2.slider("Minimum lift", min_value=1.0, max_value=5.0, value=max(1.0, float(cfg.min_lift)),
                             step=0.05, key="tp_lift")
    if (min_conf, min_lift) == (cfg.min_confidence, cfg.min_lift):
        rules = outcome.ranked
    else:
        local = filter_rules(outcome.all_rules, cfg.min_support, min_conf, min_lift).rules
        rules = rank_rules(local, ctx.weights)

    result = recommend(selected, rules, ctx.postings, ctx.catalog, SETTINGS.recommender)
    for message in result.messages:
        st.warning(message, icon=":material/warning:")

    tab_recs, tab_programme, tab_gap, tab_evidence = st.tabs(
        ["Complementary skills", "Combined programme", "Role skill gap", "Supporting rules"]
    )
    with tab_recs:
        _recommendations(result)
    with tab_programme:
        _programme(ctx, result)
    with tab_gap:
        _role_gap(ctx, selected)
    with tab_evidence:
        if result.evidence.empty:
            st.caption("No supporting rules.")
        else:
            st.caption(f"{len(result.evidence):,} mined rules start from the selected skills and add at least one new skill.")
            rules_table(result.evidence, height=460, key="tp_evidence")


def _recommendations(result: RecommendationResult) -> None:
    recs = result.as_frame()
    if recs.empty:
        return
    if len(recs) < 3:
        st.caption("Few rules qualify at the current thresholds — lowering the evidence thresholds above "
                   "will surface more (weaker) associations.")
    for rec in result.recommendations:
        with st.container(border=True):
            c1, c2, c3, c4 = st.columns([2.2, 1, 1, 1])
            c1.markdown(f"**{rec.label}**  \n<small>{rec.category}</small>", unsafe_allow_html=True)
            c2.metric("Confidence", f"{rec.confidence:.0%}")
            c3.metric("Lift", f"{rec.lift:.2f}")
            c4.metric("Postings", f"{rec.support_count:,}")
            st.caption(f"{rec.explanation} Strongest rule: {rec.best_rule} · {rec.supporting_rules} supporting rule(s).")
    chart(charts.recommendation_comparison(recs), recs[["label", "confidence", "lift", "support", "support_count", "supporting_rules"]], key="tp_chart")
    download_csv(recs.drop(columns=["skill"]), "skill_recommendations.csv", "Download recommendations (CSV)", key="dl_recs")


def _programme(ctx: AppContext, result: RecommendationResult) -> None:
    programme = result.programme
    if programme is None:
        st.info("No combined programme can be formed with sufficient posting evidence for this selection.")
        return
    added = [label for skill, label in zip(programme.skills, programme.labels) if skill not in result.selected]
    held = [label for skill, label in zip(programme.skills, programme.labels) if skill in result.selected]
    st.markdown(f"### Combined programme: {' + '.join(programme.labels)}")
    st.markdown(f"Builds on **{', '.join(held)}** and adds **{', '.join(added)}**.")
    c1, c2, c3 = st.columns(3)
    c1.metric("Postings requiring the full combination", f"{programme.postings_with_combination:,}", border=True)
    c2.metric("Share of all postings", f"{programme.share_of_all_postings:.2%}", border=True)
    c3.metric("Share of postings requiring learner's skills",
              f"{programme.share_of_learner_postings:.1%}" if programme.share_of_learner_postings is not None else "—", border=True)

    left, right = st.columns(2, gap="large")
    with left:
        st.markdown("**Suggested training modules**")
        for i, module in enumerate(programme.modules, start=1):
            st.markdown(f"{i}. **{module['module']}** — {', '.join(module['skills'])}")
        st.markdown("**Prerequisites** (curated domain knowledge, not mined)")
        if programme.prerequisites:
            st.dataframe(pd.DataFrame(programme.prerequisites), hide_index=True, width="stretch")
        else:
            st.caption("No curated prerequisites recorded for the added skills.")
    with right:
        chart(charts.role_share_bar(programme.target_roles), programme.target_roles, key="tp_roles")

    payload = {
        "generated_on": date.today().isoformat(),
        "dataset": ctx.dataset_label,
        "scope": ctx.scope_description(),
        "mining_config": ctx.mining_config.__dict__,
        "learner_skills": held,
        "programme_skills": programme.labels,
        "postings_with_combination": programme.postings_with_combination,
        "share_of_all_postings": programme.share_of_all_postings,
        "modules": programme.modules,
        "prerequisites": programme.prerequisites,
        "target_roles": programme.target_roles.to_dict("records"),
        "recommendations": [
            {k: v for k, v in rec.__dict__.items() if k != "skill"} for rec in result.recommendations
        ],
        "disclaimer": DISCLAIMER,
    }
    download_json(payload, "training_programme.json", "Download programme (JSON)", key="dl_programme")


def _role_gap(ctx: AppContext, selected: list[str]) -> None:
    roles = ctx.postings["role"].value_counts()
    role = st.selectbox("Target role", list(roles.index), format_func=lambda r: f"{r} ({roles[r]:,} postings)", key="tp_role")
    gap = role_skill_gap(selected, role, ctx.postings, ctx.catalog, top_n=12)
    if gap.empty:
        st.caption("No postings for this role in the current scope.")
        return
    st.caption(f"Skills most requested in {role} postings that the learner does not yet have.")
    st.dataframe(
        gap.drop(columns=["skill"]), hide_index=True, width="stretch",
        column_config={
            "label": "Missing skill",
            "share_in_role": st.column_config.ProgressColumn(f"Share of {role} postings", min_value=0.0, max_value=1.0, format="percent"),
            "share_overall": st.column_config.NumberColumn("Share of all postings", format="percent"),
            "role_lift": st.column_config.NumberColumn("Over-representation in role", format="%.2f×"),
            "postings": st.column_config.NumberColumn("Postings", format="localized"),
        },
    )
    download_csv(gap, f"skill_gap_{role.lower().replace(' ', '_')}.csv", "Download skill gap (CSV)", key="dl_gap")
